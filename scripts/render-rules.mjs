// Fills the two account IDs into firestore.rules.template and writes
// firestore.rendered.rules (git-ignored, and the file firebase.json deploys).
//
//   node scripts/render-rules.mjs          real IDs from config/accounts.json
//   node scripts/render-rules.mjs --test   fixed test IDs, for the emulator tests
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const testMode = process.argv.includes('--test');

let uids;
if (testMode) {
  uids = ['test-uid-a', 'test-uid-b'];
} else {
  const file = join(root, 'config', 'accounts.json');
  if (!existsSync(file)) {
    console.error('Missing config/accounts.json. Copy config/accounts.example.json and put in the two Firebase user IDs.');
    process.exit(1);
  }
  const parsed = JSON.parse(readFileSync(file, 'utf8'));
  uids = parsed.uids;
  const ok =
    Array.isArray(uids) &&
    uids.length === 2 &&
    uids[0] !== uids[1] &&
    uids.every((u) => typeof u === 'string' && /^[A-Za-z0-9]{20,40}$/.test(u));
  if (!ok) {
    console.error('config/accounts.json must hold exactly two different Firebase user IDs (20-40 letters and digits each).');
    process.exit(1);
  }
}

const template = readFileSync(join(root, 'firestore.rules.template'), 'utf8');
const rendered = template.replaceAll('__UID_A__', uids[0]).replaceAll('__UID_B__', uids[1]);
const banner = testMode
  ? '// TEST RULES, DO NOT DEPLOY. Generated by scripts/render-rules.mjs --test\n'
  : '// Generated by scripts/render-rules.mjs from firestore.rules.template\n';
writeFileSync(join(root, 'firestore.rendered.rules'), banner + rendered);
console.log(`Wrote firestore.rendered.rules (${testMode ? 'TEST ids' : 'real ids'}).`);
